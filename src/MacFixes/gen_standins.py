# Writes StandIns.g.cs: blittable stand-ins for il2cpp structs passed by value on SysV x64.
#   R*  : register-passed (<= 16 bytes), one letter per eightbyte, L = INTEGER, D = SSE
#   M<n>: memory-passed (> 16 bytes), n rounded up to a multiple of 8
lines = ['// Generated by gen_standins.py. Blittable stand-ins for il2cpp structs passed by value on SysV x64.',
         'using System.Runtime.InteropServices;', '', 'namespace MelonMacFixes.StandIns', '{']
for name, fields in [('L', ['long']), ('D', ['double']), ('LL', ['long', 'long']), ('LD', ['long', 'double']),
                     ('DL', ['double', 'long']), ('DD', ['double', 'double'])]:
    body = ' '.join(f'[FieldOffset({8 * i})] public {t} f{i};' for i, t in enumerate(fields))
    lines.append(f'    [StructLayout(LayoutKind.Explicit, Size = {8 * len(fields)})] public struct R{name} {{ {body} }}')
for n in range(24, 1025, 8):
    lines.append(f'    [StructLayout(LayoutKind.Explicit, Size = {n})] public struct M{n} {{ [FieldOffset(0)] public long f0; }}')
lines.append('}')
open('StandIns.g.cs', 'w').write('\n'.join(lines) + '\n')
